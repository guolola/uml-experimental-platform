// Renders the requirement authoring page and coordinates rule editing, quality checks, and generation actions.
import { type MouseEvent, useEffect, useMemo, useRef, useState } from "react";
import { useTranslation } from "react-i18next";
import {
  Wand2,
  Loader2,
  AlertTriangle,
  RefreshCw,
  ArrowUp,
  FileText,
  Network,
  Box,
  Server,
  GitBranch,
  Activity,
  Eye,
  X,
} from "lucide-react";
import { Button } from "../../../shared/ui/button";
import { Badge } from "../../../shared/ui/badge";
import { cn } from "../../../shared/ui/utils";
import type {
  AtomicRequirement,
  AtomicRequirementField,
  RequirementQualityIssue,
} from "@uml-platform/contracts";
import {
  DIAGRAM_META,
  DIAGRAM_ORDER,
  getDiagramDescription,
  getDiagramLabel,
  type DiagramType,
} from "../../../entities/diagram/model";
import {
  type RequirementRule,
} from "../../../entities/requirement-rule/model";
import { useWorkspaceSession } from "../../workspace-session/state";
import {
  buildRequirementModelRepairRecords,
  requirementDiagramsButtonLabel,
  requirementTargetBlockReason,
  requirementTargetCardState,
} from "../lib/requirement-target-view-model";
import {
  requirementRowState,
  type AutoGeneratedUpstreamReview,
} from "../lib/requirement-review-view-model";
import { ModelPicker } from "../../../shared/ui/model-picker";
import {
  loadUserSettings,
  patchUserSettings,
  USER_SETTINGS_CHANGED_EVENT,
} from "../../../shared/lib/user-settings";
import { ScaledToolbar } from "../../../shared/ui/scale-to-fit";
import {
  MobileCompactGrid,
} from "../../workspace-shell/components/mobile-density";
import { ModelBentoCard } from "../../workspace-shell/components/model-bento-card";
import {
  ALL_RULE_CATEGORIES,
  REQUIREMENT_RULES_PER_PAGE,
  RequirementRulesTable,
  type RequirementRuleCategoryFilter,
} from "./requirement-rules-table";
import {
  RequirementReviewDialog,
  type RequirementHintDetail,
} from "./requirement-review-dialog";
import {
  RequirementTraceabilityDialogs,
  type RequirementModelRepairResult,
} from "./requirement-traceability-dialogs";
import { NewRequirementRuleDialog } from "./new-requirement-rule-dialog";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "../../../shared/ui/dialog";

const DEFAULT_NEW_RULE_DIAGRAMS: DiagramType[] = ["function", "usecase", "activity"];
const REQUIREMENT_DIAGRAM_ICON = {
  context: Network,
  function: FileText,
  usecase: Network,
  activity: Activity,
  class: Box,
  deployment: Server,
  prototype: Eye,
  analysis: GitBranch,
} satisfies Record<DiagramType, typeof Network>;

export function TextRequirementView({
  view = "all",
}: {
  view?: "system" | "models" | "all";
}) {
  const { t } = useTranslation();
  const {
    requirementText,
    setRequirementText,
    rules,
    createRequirementRule,
    updateRequirementRule,
    deleteRequirementRule,
    selectedDiagrams,
    setSelectedDiagrams,
    generating,
    generateRules,
    generateDiagrams,
    isRulesStale,
    rulesStaleReason,
    staleDiagrams,
    generatedDiagrams,
    requirementModelTraceability,
    autoGeneratedUpstreamReviews,
    decideAutoGeneratedUpstreamReview,
    requirementBaseline,
    requirementReviewCandidates,
    requirementReviewBlockedReason,
    repairRequirementRule,
    decideRequirementReviewCandidate,
    confirmRequirementQualityHint,
    canUpdateWorkspace,
    canStartRuns,
    workspacePermissionReason,
    billingGenerationBlock,
    clearBillingGenerationBlock,
  } = useWorkspaceSession();
  const [query, setQuery] = useState("");
  const [defaultModel, setDefaultModel] = useState(
    () => loadUserSettings().defaultModel,
  );
  const [showStaleBanner, setShowStaleBanner] = useState(
    () => loadUserSettings().showStaleBanner,
  );
  const [newRuleDialogOpen, setNewRuleDialogOpen] = useState(false);
  const [newRuleCategory, setNewRuleCategory] =
    useState<RequirementRule["category"]>("功能需求");
  const [newRuleDiagrams, setNewRuleDiagrams] = useState<DiagramType[]>(
    DEFAULT_NEW_RULE_DIAGRAMS,
  );
  const [newRuleText, setNewRuleText] = useState("");
  const [newRuleError, setNewRuleError] = useState<string | null>(null);
  const [modelRepairResult, setModelRepairResult] =
    useState<RequirementModelRepairResult | null>(null);
  const [hintDetailRuleId, setHintDetailRuleId] = useState<string | null>(null);
  const [traceabilityDialogOpen, setTraceabilityDialogOpen] = useState(false);
  const [ruleReplacementDialogOpen, setRuleReplacementDialogOpen] =
    useState(false);
  const [currentRulePage, setCurrentRulePage] = useState(1);
  const [rulePageSize, setRulePageSize] = useState(REQUIREMENT_RULES_PER_PAGE);
  const [ruleCategoryFilter, setRuleCategoryFilter] =
    useState<RequirementRuleCategoryFilter>(ALL_RULE_CATEGORIES);

  useEffect(() => {
    const syncSettings = () => {
      const settings = loadUserSettings();
      setDefaultModel(settings.defaultModel);
      setShowStaleBanner(settings.showStaleBanner);
    };

    window.addEventListener(USER_SETTINGS_CHANGED_EVENT, syncSettings);
    return () => {
      window.removeEventListener(USER_SETTINGS_CHANGED_EVENT, syncSettings);
    };
  }, []);

  const hasGeneratedRules = rules.length > 0;
  const hasRequirementSourceText = requirementText.trim().length > 0;
  const canEditRequirements = canUpdateWorkspace;
  const canRunGeneration = canUpdateWorkspace && canStartRuns;
  const editBlockedReason =
    workspacePermissionReason ?? t("requirements.permissions.edit");
  const generationBlockedByPermissionReason =
    workspacePermissionReason ?? t("requirements.permissions.run");

  const runGenerateRules = () => {
    if (!canRunGeneration) return;
    if (hasGeneratedRules) {
      setRuleReplacementDialogOpen(true);
      return;
    }
    void generateRules();
  };

  const confirmRuleReplacement = () => {
    setRuleReplacementDialogOpen(false);
    if (!canRunGeneration) return;
    void generateRules();
  };

  const runGenerateDiagrams = (only?: DiagramType[]) => {
    if (!canRunGeneration) return;
    void generateDiagrams(only);
  };

  const decideAutoReviews = (
    event: MouseEvent<HTMLButtonElement>,
    reviews: AutoGeneratedUpstreamReview[],
    decision: "accepted" | "dismissed",
  ) => {
    event.stopPropagation();
    void Promise.all(
      reviews.map((review) =>
        decideAutoGeneratedUpstreamReview(review.id, decision),
      ),
    );
  };

  const updateModel = (model: string) => {
    if (!canRunGeneration) return;
    patchUserSettings({ defaultModel: model });
  };

  const selectableDiagramSet = useMemo(() => new Set(DIAGRAM_ORDER), []);

  const toggleDiagram = (diagram: DiagramType, checked: boolean) => {
    if (!canEditRequirements) return;
    if (checked && !selectableDiagramSet.has(diagram)) {
      return;
    }
    setSelectedDiagrams(
      checked
        ? Array.from(new Set([...selectedDiagrams, diagram]))
        : selectedDiagrams.filter((value) => value !== diagram),
    );
  };

  useEffect(() => {
    const nextSelectedDiagrams = selectedDiagrams.filter((diagram) =>
      selectableDiagramSet.has(diagram),
    );
    if (nextSelectedDiagrams.length !== selectedDiagrams.length) {
      setSelectedDiagrams(nextSelectedDiagrams);
    }
  }, [selectableDiagramSet, selectedDiagrams, setSelectedDiagrams]);

  const toggleNewRuleDiagram = (diagram: DiagramType, checked: boolean) => {
    setNewRuleDiagrams((current) =>
      checked
        ? Array.from(new Set([...current, diagram]))
        : current.filter((value) => value !== diagram),
    );
  };

  const resetNewRuleForm = () => {
    setNewRuleCategory("功能需求");
    setNewRuleDiagrams(DEFAULT_NEW_RULE_DIAGRAMS);
    setNewRuleText("");
    setNewRuleError(null);
  };

  const submitNewRule = () => {
    const trimmedText = newRuleText.trim();
    if (!trimmedText) {
      setNewRuleError(t("requirements.validation.textRequired"));
      return;
    }
    if (newRuleDiagrams.length === 0) {
      setNewRuleError(t("requirements.validation.modelRequired"));
      return;
    }
    createRequirementRule({
      category: newRuleCategory,
      relatedDiagrams: newRuleDiagrams,
      text: trimmedText,
    });
    setNewRuleDialogOpen(false);
    resetNewRuleForm();
  };

  const newRuleCanSubmit = newRuleText.trim().length > 0 && newRuleDiagrams.length > 0;

  const filteredRules = useMemo(() => {
    const normalizedQuery = query.trim().toLowerCase();
    return rules.filter((rule) => {
      const matchesQuery =
        !normalizedQuery || rule.text.toLowerCase().includes(normalizedQuery);
      const matchesCategory =
        ruleCategoryFilter === ALL_RULE_CATEGORIES ||
        rule.category === ruleCategoryFilter;
      return matchesQuery && matchesCategory;
    });
  }, [rules, query, ruleCategoryFilter]);

  useEffect(() => {
    setCurrentRulePage(1);
  }, [query, ruleCategoryFilter]);

  const totalRulePages = Math.max(1, Math.ceil(filteredRules.length / rulePageSize));
  const safeRulePage = Math.min(currentRulePage, totalRulePages);
  const firstRuleIndex =
    filteredRules.length === 0 ? 0 : (safeRulePage - 1) * rulePageSize + 1;
  const lastRuleIndex = Math.min(filteredRules.length, safeRulePage * rulePageSize);
  const pagedRules = filteredRules.slice(firstRuleIndex - 1, lastRuleIndex);
  const emptyRuleSlots = Math.max(0, rulePageSize - pagedRules.length);
  const requirementByRuleId = useMemo(() => {
    const entries =
      requirementBaseline?.requirements
        .filter((requirement) => requirement.sourceRuleId)
        .map((requirement) => [requirement.sourceRuleId!, requirement] as const) ?? [];
    return new Map(entries);
  }, [requirementBaseline]);
  const qualityIssuesByRequirementId = useMemo(() => {
    const map = new Map<string, RequirementQualityIssue[]>();
    for (const issue of requirementBaseline?.qualityReport.issues ?? []) {
      if (!issue.requirementId) continue;
      map.set(issue.requirementId, [
        ...(map.get(issue.requirementId) ?? []),
        issue,
      ]);
    }
    return map;
  }, [requirementBaseline]);
  const hintDetail = useMemo<RequirementHintDetail | null>(() => {
    if (!hintDetailRuleId) return null;
    const rule = rules.find((item) => item.id === hintDetailRuleId);
    const requirement = requirementByRuleId.get(hintDetailRuleId);
    if (!rule || !requirement) return null;
    const qualityIssues = qualityIssuesByRequirementId.get(requirement.id) ?? [];
    const fieldEntries = Object.entries(requirement.fieldProvenance).filter(
      (entry): entry is [
        AtomicRequirementField,
        NonNullable<AtomicRequirement["fieldProvenance"][AtomicRequirementField]>,
      ] => {
        const [, provenance] = entry;
        return Boolean(
          provenance &&
            (provenance.source === "ai-suggested" ||
              provenance.status === "pending-review" ||
              provenance.status === "rejected"),
        );
      },
    );
    return {
      rule,
      requirement,
      candidate: requirementReviewCandidates[hintDetailRuleId] ?? null,
      rowState: requirementRowState(requirement, qualityIssues),
      qualityIssues,
      fieldEntries,
    };
  }, [
    hintDetailRuleId,
    qualityIssuesByRequirementId,
    requirementByRuleId,
    requirementReviewCandidates,
    rules,
  ]);
  const lastHintDetailRef = useRef<typeof hintDetail>(null);
  if (hintDetail) {
    lastHintDetailRef.current = hintDetail;
  }
  const visibleHintDetail = hintDetailRuleId
    ? hintDetail ??
      (lastHintDetailRef.current?.rule.id === hintDetailRuleId
        ? lastHintDetailRef.current
        : null)
    : null;
  useEffect(() => {
    if (currentRulePage > totalRulePages) {
      setCurrentRulePage(totalRulePages);
    }
  }, [currentRulePage, totalRulePages]);

  const generateDiagramsButtonLabel = requirementDiagramsButtonLabel({
    generatedDiagrams,
    selectedDiagrams,
    staleDiagrams,
    t,
  });
  const visibleRequirementReviewBlockedReason = requirementReviewBlockedReason
    ? t("requirements.reviewBlocked")
    : null;
  const generationBlockedTitle =
    visibleRequirementReviewBlockedReason ?? undefined;
  const selectedTargetBlockReason =
    selectedDiagrams
      .map((diagram) =>
        requirementTargetBlockReason({
          diagram,
          generatedDiagrams,
          hasRequirementSourceText,
          isRulesStale,
          rules,
          staleDiagrams,
        }),
      )
      .find(Boolean) ?? null;
  const requirementModelRepairRecords = useMemo(() => {
    return buildRequirementModelRepairRecords({
      generatedDiagrams,
      requirementModelTraceability,
      rules,
    });
  }, [generatedDiagrams, requirementModelTraceability, rules]);
  const rulesStaleMessage =
    rulesStaleReason === "rules"
      ? t("requirements.stale.downstream")
      : rulesStaleReason === "source-missing"
        ? t("requirements.stale.empty")
        : t("requirements.stale.changed");
  const staleDiagramReason =
    isRulesStale && rulesStaleReason === "text"
      ? t("requirements.stale.changedTitle")
      : rulesStaleReason === "source-missing"
        ? t("requirements.stale.emptyTitle")
      : t("requirements.stale.reviewTitle");

  const renderRequirementInput = (mode: "empty" | "generated") => (
    <div
      className={cn(
        "relative",
        mode === "empty" &&
          "overflow-hidden rounded-xl border border-border bg-card p-6 shadow-sm",
      )}
    >
      {mode === "empty" && (
        <div className="absolute -right-20 -top-20 size-64 rounded-full bg-primary/5 blur-3xl" />
      )}
      <div className="relative flex items-center justify-between gap-4">
        <div className="flex items-center gap-2">
          <FileText className="size-5 text-primary" />
          <h2
            id="requirement-text-heading"
            className="text-xl font-semibold tracking-normal text-foreground"
          >
            {mode === "empty" ? t("requirements.source.projectDescription") : t("requirements.source.description")}
          </h2>
        </div>
      </div>
      <textarea
        id="requirement-text"
        aria-labelledby="requirement-text-heading"
        name="requirementText"
        value={requirementText}
        onChange={(event) => {
          if (canEditRequirements) setRequirementText(event.target.value);
        }}
        placeholder={t("requirements.source.placeholder")}
        disabled={!canEditRequirements}
        title={!canEditRequirements ? editBlockedReason : undefined}
        className={cn(
          "relative mt-3 w-full resize-y rounded-lg border border-input bg-background px-4 py-4 text-sm leading-relaxed text-foreground outline-none transition-colors placeholder:text-muted-foreground focus:border-primary/60 focus:ring-2 focus:ring-primary/15",
          !canEditRequirements &&
            "cursor-not-allowed bg-muted/40 text-muted-foreground",
          mode === "empty" ? "h-[clamp(360px,48vh,620px)] min-h-80" : "h-[240px]",
        )}
      />
      <ScaledToolbar
        minWidth={420}
        minReadableScale={0.7}
        className="relative mt-6"
        contentClassName="w-full gap-2"
      >
          <ModelPicker
            value={defaultModel}
            onValueChange={updateModel}
            disabled={!canRunGeneration}
          />
          {isRulesStale && (
            <Badge variant="warning" className="rounded-md px-1.5 py-0 text-[11px]">
              {t("requirements.source.changed")}
            </Badge>
          )}
          <div className="ml-auto flex items-center gap-2">
            <Button
              type="button"
              variant="outline"
              size="sm"
              className="h-10 rounded-full px-6"
              onClick={() => setRequirementText("")}
              disabled={!requirementText || generating || !canEditRequirements}
              title={!canEditRequirements ? editBlockedReason : undefined}
            >
              {t("requirements.source.clear")}
            </Button>
            <button
              type="button"
              onClick={runGenerateRules}
              disabled={!requirementText.trim() || generating || !canRunGeneration}
              title={
                !canRunGeneration
                  ? generationBlockedByPermissionReason
                  : isRulesStale
                    ? t("requirements.source.updateRules")
                    : t("requirements.source.generateRules")
              }
              className="inline-flex h-10 items-center gap-2 rounded-full bg-primary px-6 text-sm font-medium text-primary-foreground shadow-sm transition-opacity hover:opacity-90 disabled:cursor-not-allowed disabled:opacity-40"
            >
              {generating ? (
                <Loader2 className="size-4 animate-spin" />
              ) : (
                <ArrowUp className="size-4" />
              )}
              {isRulesStale ? t("requirements.source.updateRules") : t("requirements.source.startAnalysis")}
            </button>
          </div>
      </ScaledToolbar>
    </div>
  );

  const renderRequirementRules = () => (
    <RequirementRulesTable
      canEditRequirements={canEditRequirements}
      currentRulePage={currentRulePage}
      deleteRequirementRule={deleteRequirementRule}
      editBlockedReason={editBlockedReason}
      emptyRuleSlots={emptyRuleSlots}
      filteredRules={filteredRules}
      firstRuleIndex={firstRuleIndex}
      generating={generating}
      lastRuleIndex={lastRuleIndex}
      onAddRule={() => setNewRuleDialogOpen(true)}
      onOpenHintDetail={setHintDetailRuleId}
      pagedRules={pagedRules}
      qualityIssuesByRequirementId={qualityIssuesByRequirementId}
      query={query}
      requirementByRuleId={requirementByRuleId}
      requirementReviewCandidates={requirementReviewCandidates}
      ruleCategoryFilter={ruleCategoryFilter}
      rulePageSize={rulePageSize}
      rulesCount={rules.length}
      safeRulePage={safeRulePage}
      setCurrentRulePage={setCurrentRulePage}
      setQuery={setQuery}
      setRuleCategoryFilter={setRuleCategoryFilter}
      setRulePageSize={setRulePageSize}
      totalRulePages={totalRulePages}
      updateRequirementRule={updateRequirementRule}
    />
  );

  return (
    <div className="flex h-full min-h-0 min-w-0 max-w-full flex-col overflow-x-hidden overflow-y-auto bg-background">
      {view !== "models" && showStaleBanner && isRulesStale && (
        <div className="flex items-center gap-2 border-b border-warning/40 bg-warning/10 px-3 py-2 text-sm">
          <AlertTriangle className="size-4 text-warning" />
          <span>{rulesStaleMessage}</span>
          <Button
            size="sm"
            variant="outline"
            className="ml-auto h-7"
            onClick={runGenerateRules}
            disabled={generating || !canRunGeneration}
            title={!canRunGeneration ? generationBlockedByPermissionReason : undefined}
          >
            <RefreshCw className="size-3.5" /> {t("requirements.source.regenerateRules")}
          </Button>
        </div>
      )}

      {view !== "system" && showStaleBanner && staleDiagrams.length > 0 && (
        <div className="flex items-center gap-2 border-b border-warning/40 bg-warning/10 px-3 py-2 text-sm">
          <AlertTriangle className="size-4 text-warning" />
          <span>
            {t("requirements.stale.modelCount", { count: staleDiagrams.length, reason: staleDiagramReason })}
            {staleDiagrams.map((diagram) => getDiagramLabel(diagram, t)).join(t("traceability.refSeparator"))}
          </span>
          <Button
            size="sm"
            variant="outline"
            className="ml-auto h-7"
            onClick={() => runGenerateDiagrams(staleDiagrams)}
            disabled={
              generating ||
              Boolean(requirementReviewBlockedReason) ||
              !canRunGeneration
            }
            title={
              !canRunGeneration
                ? generationBlockedByPermissionReason
                : generationBlockedTitle
            }
          >
            <RefreshCw className="size-3.5" /> {t("requirements.stale.updateModels")}
          </Button>
        </div>
      )}

      <div className="min-w-0 max-w-full overflow-x-hidden py-4 lg:py-5">
        <div className="mx-auto flex w-[calc(100%-1.5rem)] min-w-0 max-w-none flex-col gap-5 sm:w-[calc(100%-2rem)] lg:w-[calc(100%-3rem)]">
          <header className="flex flex-col gap-1.5">
            <h1 className="text-2xl font-semibold tracking-normal text-foreground lg:text-3xl">
              {view === "system" ? t("requirements.page.systemTitle") : view === "models" ? t("requirements.page.modelsTitle") : t("requirements.page.allTitle")}
            </h1>
            <p className="max-w-3xl text-sm leading-6 text-muted-foreground">
              {view === "system"
                ? t("requirements.page.systemDescription")
                : view === "models"
                  ? t("requirements.page.modelsDescription")
                  : t("requirements.page.allDescription")}
            </p>
            {!canEditRequirements && (
              <div className="mt-2 inline-flex max-w-3xl items-center gap-2 rounded-lg border border-warning/30 bg-warning/10 px-3 py-2 text-xs text-warning">
                <AlertTriangle className="size-3.5" />
                {editBlockedReason}
              </div>
            )}
            {billingGenerationBlock && (
              <div className="mt-2 flex max-w-4xl flex-wrap items-center gap-3 rounded-lg border border-warning/30 bg-warning/10 px-3 py-2 text-sm text-foreground">
                <AlertTriangle className="size-4 text-warning" />
                <div className="min-w-0 flex-1">
                  <div className="font-medium">{billingGenerationBlock.message}</div>
                  <div className="text-xs text-muted-foreground">
                    {t("requirements.credits", { count: billingGenerationBlock.billingSummary.creditBalance })}
                  </div>
                </div>
                <Button
                  type="button"
                  size="icon"
                  variant="ghost"
                  className="size-8"
                  aria-label={t("requirements.closeCredits")}
                  onClick={clearBillingGenerationBlock}
                >
                  <X className="size-4" />
                </Button>
              </div>
            )}
          </header>
          {view !== "models" && <div className="grid min-w-0 max-w-full grid-cols-1 gap-4 overflow-x-hidden">
            <div className="grid min-w-0 grid-cols-[minmax(0,1fr)] gap-4">
              {renderRequirementInput(hasGeneratedRules ? "generated" : "empty")}
              {hasGeneratedRules && renderRequirementRules()}
            </div>
          </div>}

          {view === "models" && rules.length === 0 && (
            <div className="rounded-xl border border-warning/30 bg-warning/10 px-4 py-3 text-sm text-foreground">
              {t("requirements.noRules")}
            </div>
          )}

          {view !== "system" && <section className="flex flex-col gap-4">
            <ScaledToolbar
              minWidth={500}
              minReadableScale={0.68}
              contentClassName="w-full justify-between gap-6"
            >
              <div className="flex shrink-0 items-center gap-2">
                <Network className="size-5 text-primary" />
                <h2 className="text-xl font-semibold tracking-normal text-foreground">
                  {t("requirements.targetModels")}
                </h2>
                <Badge
                  variant="secondary"
                  className="rounded-md border-0 px-3 py-1 font-mono text-xs"
                >
                  {selectedDiagrams.length}/{DIAGRAM_ORDER.length}
                </Badge>
              </div>
              <div className="flex shrink-0 items-center gap-2">
                {requirementModelRepairRecords.length > 0 && (
                  <Button
                    type="button"
                    size="sm"
                    variant="outline"
                    className="h-9 rounded-lg bg-card"
                    aria-label={t("requirements.traceProofAria", { count: requirementModelRepairRecords.length })}
                    onClick={() => setTraceabilityDialogOpen(true)}
                  >
                    <Eye className="size-3.5" />
                    {t("requirements.traceProof")}
                    <span className="rounded border border-border bg-muted px-1.5 py-0.5 font-mono text-[10px]">
                      {t("requirements.itemCount", { count: requirementModelRepairRecords.length })}
                    </span>
                  </Button>
                )}
                <ModelPicker
                  value={defaultModel}
                  onValueChange={updateModel}
                  align="end"
                  triggerClassName="bg-card"
                  disabled={!canRunGeneration}
                />
                <button
                  type="button"
                  onClick={() => runGenerateDiagrams()}
                  disabled={
                    selectedDiagrams.length === 0 ||
                    generating ||
                    Boolean(requirementReviewBlockedReason) ||
                    Boolean(selectedTargetBlockReason) ||
                    !canRunGeneration
                  }
                  title={
                    !canRunGeneration
                      ? generationBlockedByPermissionReason
                      : selectedTargetBlockReason ?? generationBlockedTitle
                  }
                  className="inline-flex h-9 items-center gap-2 rounded-lg bg-primary px-4 text-sm font-medium text-primary-foreground shadow-sm transition-opacity hover:opacity-90 disabled:cursor-not-allowed disabled:opacity-40"
                >
                  {generating ? (
                    <Loader2 className="size-4 animate-spin" />
                  ) : (
                    <Wand2 className="size-4" />
                  )}
                  {generateDiagramsButtonLabel}
                </button>
              </div>
            </ScaledToolbar>
            {requirementReviewBlockedReason && (
              <div className="flex items-center gap-1.5 rounded-lg border border-warning/30 bg-warning/10 px-3 py-2 text-xs text-warning">
                <AlertTriangle className="size-3.5" />
                {visibleRequirementReviewBlockedReason}
              </div>
            )}

            <MobileCompactGrid
              minWidth={720}
              variant="model-targets"
            >
              {DIAGRAM_ORDER.map((diagram) => {
                const meta = DIAGRAM_META[diagram];
                const localizedLabel = getDiagramLabel(diagram, t);
                const localizedDescription = getDiagramDescription(diagram, t);
                const {
                  autoFillLabels,
                  blockReason,
                  canSelectDiagram,
                  checked,
                  hasPendingAutoReview,
                  isAnalysisDiagram,
                  linkedRules,
                  pendingAutoReviews,
                  sourceCount,
                } = requirementTargetCardState({
                  autoGeneratedUpstreamReviews,
                  canEditRequirements,
                  diagram,
                  generatedDiagrams,
                  hasRequirementSourceText,
                  isRulesStale,
                  rules,
                  selectedDiagrams,
                  staleDiagrams,
                });
                const DiagramIcon = REQUIREMENT_DIAGRAM_ICON[diagram];
                return (
                  <ModelBentoCard
                    key={diagram}
                    label={localizedLabel}
                    english={meta.english}
                    description={localizedDescription}
                    icon={DiagramIcon}
                    selected={checked}
                    disabled={!canSelectDiagram}
                    countLabel={sourceCount}
                    pendingReview={hasPendingAutoReview}
                    title={
                      !canEditRequirements ? editBlockedReason : undefined
                    }
                    ariaLabel={t(checked ? "requirements.cancelSelect" : "requirements.select", { label: localizedLabel })}
                    checkboxLabel={localizedLabel}
                    onSelectedChange={(value) => toggleDiagram(diagram, value)}
                    status={
                      <div className="space-y-1.5">
                        {hasPendingAutoReview && (
                          <div className="rounded-md border border-warning/30 bg-warning/10 p-2 text-warning">
                            <div className="flex items-start gap-1.5">
                              <AlertTriangle className="mt-0.5 size-3.5 shrink-0" />
                              <span>
                                {t("requirements.autoFillPending")}
                                {pendingAutoReviews
                                  .map((review) => review.label)
                                  .join("、")}
                              </span>
                            </div>
                            <div className="mt-1 text-[11px] leading-relaxed">
                              {t("requirements.autoFillDescription")}
                            </div>
                            <div className="mt-2 flex flex-wrap gap-2">
                              <Button
                                type="button"
                                size="sm"
                                variant="outline"
                                className="h-7 rounded-md px-2 text-[11px]"
                                aria-label={t("requirements.acceptAutoFillAria", { label: meta.label })}
                                onClick={(event) =>
                                  decideAutoReviews(
                                    event,
                                    pendingAutoReviews,
                                    "accepted",
                                  )
                                }
                              >
                                {t("requirements.acceptAutoFill")}
                              </Button>
                              <Button
                                type="button"
                                size="sm"
                                variant="ghost"
                                className="h-7 rounded-md px-2 text-[11px]"
                                aria-label={t("requirements.dismissAutoFillAria", { label: meta.label })}
                                onClick={(event) =>
                                  decideAutoReviews(
                                    event,
                                    pendingAutoReviews,
                                    "dismissed",
                                  )
                                }
                              >
                                {t("requirements.dismissAutoFill")}
                              </Button>
                            </div>
                          </div>
                        )}
                        {!canSelectDiagram && (
                          <div className="flex items-center gap-1.5 text-destructive">
                            <AlertTriangle className="size-3.5 shrink-0" />
                            <span>
                              {blockReason ??
                                (isAnalysisDiagram
                                  ? t("requirements.useCaseRequired")
                                  : t("requirements.rulesRequired"))}
                            </span>
                          </div>
                        )}
                        {autoFillLabels.length > 0 && !blockReason && (
                          <div className="flex items-center gap-1.5 text-warning">
                            <AlertTriangle className="size-3.5 shrink-0" />
                            <span>{t("requirements.willAutoFill", {
                              labels: autoFillLabels.map((label) =>
                                label === DIAGRAM_META.usecase.label
                                  ? getDiagramLabel("usecase", t)
                                  : label === "需求规则"
                                    ? t("requirements.autoFillSources.rules")
                                    : t("requirements.autoFillSources.mapping"),
                              ).join(t("traceability.refSeparator")),
                            })}</span>
                          </div>
                        )}
                        {isAnalysisDiagram &&
                          canSelectDiagram &&
                          linkedRules.length === 0 && (
                            <div className="text-muted-foreground">
                              {t("requirements.analysisDependency")}
                            </div>
                          )}
                        {canSelectDiagram &&
                          autoFillLabels.length === 0 &&
                          !(
                            isAnalysisDiagram && linkedRules.length === 0
                          ) && (
                            <div className="text-muted-foreground">
                              {t("requirements.sourceCount", { count: sourceCount })}
                            </div>
                          )}
                      </div>
                    }
                    details={
                      linkedRules.length > 0 ? (
                        <div className="hidden flex-wrap gap-1.5 sm:flex">
                          {linkedRules.map((rule) => (
                            <button
                              type="button"
                              key={rule.id}
                              title={rule.text}
                              onClick={(event) => {
                                event.stopPropagation();
                                const element = document.getElementById(
                                  `rule-${rule.id}`,
                                );
                                if (element) {
                                  element.scrollIntoView({
                                    behavior: "smooth",
                                    block: "center",
                                  });
                                  element.classList.add("ring-2", "ring-primary/40");
                                  setTimeout(() => {
                                    element.classList.remove(
                                      "ring-2",
                                      "ring-primary/40",
                                    );
                                  }, 1200);
                                }
                              }}
                              onKeyDown={(event) => event.stopPropagation()}
                              className="rounded border border-border bg-secondary px-2 py-0.5 font-mono text-[10px] uppercase text-muted-foreground transition-colors hover:border-primary/40 hover:bg-accent hover:text-accent-foreground"
                            >
                              {rule.id}
                            </button>
                          ))}
                        </div>
                      ) : null
                    }
                  />
                );
              })}
            </MobileCompactGrid>
            <p className="pb-4 text-center text-xs text-muted-foreground">
              {t("requirements.selectionHint")}
            </p>
          </section>}
        </div>
      </div>

      {view !== "models" && <RequirementReviewDialog
        generating={generating}
        onConfirmQualityHint={confirmRequirementQualityHint}
        onDecideReviewCandidate={decideRequirementReviewCandidate}
        onOpenChange={(open) => {
          if (!open) setHintDetailRuleId(null);
        }}
        onRepairRequirementRule={repairRequirementRule}
        visibleHintDetail={visibleHintDetail}
      />}

      <RequirementTraceabilityDialogs
        modelRepairResult={modelRepairResult}
        records={requirementModelRepairRecords}
        setModelRepairResult={setModelRepairResult}
        setTraceabilityDialogOpen={setTraceabilityDialogOpen}
        traceabilityDialogOpen={traceabilityDialogOpen}
      />

      {view !== "models" && <Dialog
        open={ruleReplacementDialogOpen}
        onOpenChange={setRuleReplacementDialogOpen}
      >
        <DialogContent className="sm:max-w-lg">
          <DialogHeader>
            <DialogTitle>{t("requirements.replace.title")}</DialogTitle>
            <DialogDescription>
              {t("requirements.replace.description", { count: rules.length })}
            </DialogDescription>
          </DialogHeader>
          <DialogFooter className="gap-2 sm:gap-2">
            <Button
              type="button"
              variant="outline"
              onClick={() => setRuleReplacementDialogOpen(false)}
            >
              {t("requirements.replace.cancel")}
            </Button>
            <Button
              type="button"
              onClick={confirmRuleReplacement}
              disabled={generating || !canRunGeneration}
            >
              {t("requirements.replace.confirm")}
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>}

      {view !== "models" && <NewRequirementRuleDialog
        canEditRequirements={canEditRequirements}
        generating={generating}
        newRuleCanSubmit={newRuleCanSubmit}
        newRuleCategory={newRuleCategory}
        newRuleDiagrams={newRuleDiagrams}
        newRuleError={newRuleError}
        newRuleText={newRuleText}
        onCategoryChange={(category) => {
          setNewRuleCategory(category);
          setNewRuleError(null);
        }}
        onOpenChange={(open) => {
          setNewRuleDialogOpen(open);
          if (!open) resetNewRuleForm();
        }}
        onSubmit={submitNewRule}
        onTextChange={(text) => {
          setNewRuleText(text);
          setNewRuleError(null);
        }}
        onToggleDiagram={(diagram, checked) => {
          toggleNewRuleDiagram(diagram, checked);
          setNewRuleError(null);
        }}
        open={newRuleDialogOpen}
      />}

    </div>
  );
}

